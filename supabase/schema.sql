-- Supabase Auth app_metadata is writable only by the Admin API, never by a normal user.
create or replace function public.sync_new_profile() returns trigger language plpgsql security definer set search_path=public,auth
as $$
declare v_role text; v_entity text; v_name text;
begin
  v_role:=coalesce(new.raw_app_meta_data->>'role','');
  v_entity:=coalesce(new.raw_app_meta_data->>'entity_id','');
  v_name:=coalesce(new.raw_user_meta_data->>'name',split_part(new.email,'@',1));
  if v_role not in ('punto_salud','proveedor','eps','admin') or not exists(select 1 from public.organizations where id=v_entity) then
    raise exception 'A profile role and entity must be assigned by a trusted administrator';
  end if;
  insert into public.profiles(id,email,name,role,entity_id) values(new.id,new.email,v_name,v_role,v_entity)
  on conflict(id) do update set email=excluded.email,name=excluded.name,role=excluded.role,entity_id=excluded.entity_id;
  if exists(select 1 from public.chat_rooms where room_id='sala-general') then
    insert into public.chat_room_members(room_id,user_id,entity_id) values('sala-general',new.id,v_entity) on conflict do nothing;
  end if;
  return new;
end $$;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert or update of raw_app_meta_data,raw_user_meta_data on auth.users for each row execute function public.sync_new_profile();

create or replace function public.create_direct_room(p_entity text) returns text
language plpgsql security definer set search_path=public,auth
as $$
declare v_room text; v_me text; v_pair text; v_user uuid;
begin
  if auth.uid() is null or public.current_role() is null then raise exception 'Authentication required'; end if;
  v_me:=public.current_entity();
  if p_entity=v_me or not exists(select 1 from public.organizations where id=p_entity and active) then raise exception 'Invalid recipient entity'; end if;
  v_pair:=least(v_me,p_entity)||'|'||greatest(v_me,p_entity);
  v_room:='direct:'||substr(encode(extensions.digest(v_pair,'sha256'),'hex'),1,24);
  insert into public.chat_rooms(room_id,kind,title,created_by) values(v_room,'direct',(select name from public.organizations where id=p_entity),auth.uid()) on conflict do nothing;
  insert into public.chat_room_members(room_id,user_id,entity_id)
    select v_room,p.id,p.entity_id from public.profiles p where p.active and p.entity_id in (v_me,p_entity) on conflict do nothing;
  for v_user in select user_id from public.chat_room_members where room_id=v_room loop
    perform realtime.send(jsonb_build_object('room_id',v_room),'room_created','user:'||v_user::text,true);
  end loop;
  return v_room;
end $$;

create or replace function public.validate_order_transition() returns trigger language plpgsql security definer set search_path=public,auth
as $$
declare allowed text[];
begin
  if public.is_admin() then return new; end if;
  if new.requester_entity_id is distinct from old.requester_entity_id or new.provider_entity_id is distinct from old.provider_entity_id or new.eps_entity_id is distinct from old.eps_entity_id then
    raise exception 'Order entities cannot be changed after creation';
  end if;
  if not ((public.current_role()='proveedor' and public.current_entity()=old.provider_entity_id) or (public.current_role()='punto_salud' and public.current_entity()=old.requester_entity_id)) then
    raise exception 'Not authorized to change this order';
  end if;
  if new.status=old.status then return new; end if;
  if public.current_role()='proveedor' and public.current_entity()=old.provider_entity_id then
    allowed:=case old.status when 'Pendiente' then array['Confirmado'] when 'Confirmado' then array['En preparación','Retrasado'] when 'En preparación' then array['Despachado','Retrasado'] when 'Despachado' then array['En tránsito','Entregado','Retrasado'] when 'En tránsito' then array['Entregado','Retrasado'] when 'Retrasado' then array['Confirmado','En preparación','Despachado','En tránsito','Entregado'] else array[]::text[] end;
  elsif public.current_role()='punto_salud' and public.current_entity()=old.requester_entity_id then
    allowed:=case old.status when 'Pendiente' then array['Cancelado'] when 'Entregado' then array[]::text[] else array['Entregado'] end;
  else raise exception 'Not authorized to change this order'; end if;
  if not (new.status=any(allowed)) then raise exception 'Invalid order status transition'; end if;
  new.updated_at:=now();return new;
end $$;
drop trigger if exists orders_validate_transition on public.orders;
create trigger orders_validate_transition before update of status on public.orders for each row execute function public.validate_order_transition();

