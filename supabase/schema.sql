-- Create a complete order atomically so an incomplete request is never visible.
create or replace function public.create_order(
  p_provider_entity_id text,
  p_eps_entity_id text,
  p_eta date,
  p_notes text,
  p_items jsonb
) returns public.orders
language plpgsql security invoker set search_path=public,auth
as $$
declare
  v_order public.orders;
  v_id bigint;
  v_item jsonb;
  v_medicine text;
  v_qty integer;
begin
  if auth.uid() is null or public.current_role() not in ('punto_salud','admin') then
    raise exception 'Only Punto Salud or an administrator can create orders';
  end if;
  if p_provider_entity_id not in ('org-medisupply','org-farmared','org-biofarma') then
    raise exception 'Invalid provider';
  end if;
  if p_eps_entity_id not in ('org-eps-bienestar','org-eps-nueva-vida') then
    raise exception 'Invalid EPS';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'At least one order item is required';
  end if;

  v_id:=nextval(pg_get_serial_sequence('public.orders','id'));
  insert into public.orders(id,code,requester_entity_id,provider_entity_id,eps_entity_id,status,eta,notes)
  values (
    v_id,'CS-'||to_char(current_date,'YYYY')||'-'||lpad(v_id::text,4,'0'),
    case when public.current_role()='admin' then 'org-punto-salud' else public.current_entity() end,
    p_provider_entity_id,p_eps_entity_id,'Pendiente',p_eta,coalesce(p_notes,'')
  ) returning * into v_order;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_medicine:=nullif(v_item->>'medicine','');
    v_qty:=nullif(v_item->>'qty','')::integer;
    if v_medicine is null or v_qty is null or v_qty<=0 then
      raise exception 'Each item needs a medicine and positive quantity';
    end if;
    if not exists(select 1 from public.inventory where name=v_medicine and supplier_entity_id=p_provider_entity_id) then
      raise exception 'Medicine is not in this provider catalog';
    end if;
    insert into public.order_items(order_id,medicine,qty) values(v_order.id,v_medicine,v_qty);
  end loop;

  insert into public.order_events(order_id,status,note,actor_id,actor)
  select v_order.id,v_order.status,v_order.notes,auth.uid(),p.name
  from public.profiles p where p.id=auth.uid();
  return v_order;
end $$;

create or replace function public.update_order_status(
  p_order_id bigint,
  p_status text,
  p_eta date default null,
  p_notes text default null
) returns public.orders
language plpgsql security invoker set search_path=public,auth
as $$
declare v_order public.orders;
begin
  update public.orders
  set status=p_status,eta=coalesce(p_eta,eta),notes=coalesce(nullif(p_notes,''),notes)
  where id=p_order_id
  returning * into v_order;
  if not found then raise exception 'Order not found or access denied'; end if;
  insert into public.order_events(order_id,status,note,actor_id,actor)
  select v_order.id,v_order.status,coalesce(nullif(p_notes,''),v_order.notes),auth.uid(),p.name
  from public.profiles p where p.id=auth.uid();
  return v_order;
end $$;

